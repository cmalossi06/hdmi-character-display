/*
 ============================================================================
 Name        : HDMI_driver.v
 Description : 1280x720 @ 60Hz text-mode HDMI timing and RGB generation
 ============================================================================
 */

module HDMI_driver (
    input         reset,
    input         clk,
    input  [7:0]  char_data,
    output [11:0] char_addr,
    output        h_sync,
    output        v_sync,
    output        video_de,
    output [7:0]  red,
    output [7:0]  green,
    output [7:0]  blue
);

    localparam [11:0] H_SYNC         = 12'd40;
    localparam [11:0] H_BACK_PORCH   = 12'd220;
    localparam [11:0] H_ACTIVE       = 12'd1280;
    localparam [11:0] H_FRONT_PORCH  = 12'd110;
    localparam [11:0] H_TOTAL        = 12'd1650;

    localparam [11:0] V_SYNC         = 12'd5;
    localparam [11:0] V_BACK_PORCH   = 12'd20;
    localparam [11:0] V_ACTIVE       = 12'd720;
    localparam [11:0] V_FRONT_PORCH  = 12'd5;
    localparam [11:0] V_TOTAL        = 12'd750;

    localparam [11:0] H_ACTIVE_START = H_SYNC + H_BACK_PORCH;
    localparam [11:0] H_ACTIVE_END   = H_ACTIVE_START + H_ACTIVE;
    localparam [11:0] V_ACTIVE_START = V_SYNC + V_BACK_PORCH;
    localparam [11:0] V_ACTIVE_END   = V_ACTIVE_START + V_ACTIVE;

    localparam integer TEXT_COLS = 80;
    localparam [28:0] COLOR_BARS_CYCLES = 29'd371250000;

    localparam [23:0] RGB_WHITE   = 24'hffffff;
    localparam [23:0] RGB_YELLOW  = 24'hffff00;
    localparam [23:0] RGB_CYAN    = 24'h00ffff;
    localparam [23:0] RGB_GREEN   = 24'h00ff00;
    localparam [23:0] RGB_MAGENTA = 24'hff00ff;
    localparam [23:0] RGB_RED     = 24'hff0000;
    localparam [23:0] RGB_BLUE    = 24'h0000ff;
    localparam [23:0] RGB_BLACK   = 24'h000000;

    reg [11:0] h_cnt;
    reg [11:0] v_cnt;
    reg [28:0] mode_cnt;
    reg        text_mode;

    reg        active_d;
    reg [3:0]  glyph_x_d;
    reg [3:0]  glyph_y_d;
    reg [23:0] color_bar_d;

    wire active_now = (h_cnt >= H_ACTIVE_START) && (h_cnt < H_ACTIVE_END) &&
                      (v_cnt >= V_ACTIVE_START) && (v_cnt < V_ACTIVE_END);

    wire [11:0] active_x = h_cnt - H_ACTIVE_START;
    wire [11:0] active_y = v_cnt - V_ACTIVE_START;
    wire [6:0]  text_col = active_x[10:4];
    wire [5:0]  text_row = active_y[9:4];

    wire [15:0] font_pixels;
    wire        text_pixel = font_pixels[4'd15 - glyph_x_d];
    wire [23:0] text_rgb = text_pixel ? RGB_WHITE : RGB_BLACK;
    wire [23:0] active_rgb = text_mode ? text_rgb : color_bar_d;

    assign char_addr = active_now ? ((text_row * TEXT_COLS) + text_col) : 12'd0;

    assign h_sync = (h_cnt < H_SYNC);
    assign v_sync = (v_cnt < V_SYNC);
    assign video_de = active_d;
    assign red   = active_d ? active_rgb[23:16] : 8'h00;
    assign green = active_d ? active_rgb[15:8]  : 8'h00;
    assign blue  = active_d ? active_rgb[7:0]   : 8'h00;

    HDMI_font_rom u_font_rom (
        .ascii  (char_data),
        .row    (glyph_y_d),
        .pixels (font_pixels)
    );

    function [23:0] color_bar_for_x;
        input [11:0] x;
        begin
            if (x < 12'd160) color_bar_for_x = RGB_WHITE;
            else if (x < 12'd320) color_bar_for_x = RGB_YELLOW;
            else if (x < 12'd480) color_bar_for_x = RGB_CYAN;
            else if (x < 12'd640) color_bar_for_x = RGB_GREEN;
            else if (x < 12'd800) color_bar_for_x = RGB_MAGENTA;
            else if (x < 12'd960) color_bar_for_x = RGB_RED;
            else if (x < 12'd1120) color_bar_for_x = RGB_BLUE;
            else color_bar_for_x = RGB_BLACK;
        end
    endfunction

    always @(posedge clk or posedge reset) begin
        if (reset) begin
            h_cnt <= 12'd0;
            v_cnt <= 12'd0;
        end else if (h_cnt == H_TOTAL - 1'b1) begin
            h_cnt <= 12'd0;
            if (v_cnt == V_TOTAL - 1'b1) begin
                v_cnt <= 12'd0;
            end else begin
                v_cnt <= v_cnt + 1'b1;
            end
        end else begin
            h_cnt <= h_cnt + 1'b1;
        end
    end

    always @(posedge clk or posedge reset) begin
        if (reset) begin
            active_d <= 1'b0;
            glyph_x_d <= 4'd0;
            glyph_y_d <= 4'd0;
            color_bar_d <= RGB_BLACK;
        end else begin
            active_d <= active_now;
            glyph_x_d <= active_x[3:0];
            glyph_y_d <= active_y[3:0];
            color_bar_d <= color_bar_for_x(active_x);
        end
    end

    always @(posedge clk or posedge reset) begin
        if (reset) begin
            mode_cnt <= 29'd0;
            text_mode <= 1'b0;
        end else if (!text_mode) begin
            if (mode_cnt == COLOR_BARS_CYCLES - 1'b1) begin
                text_mode <= 1'b1;
            end else begin
                mode_cnt <= mode_cnt + 1'b1;
            end
        end
    end

endmodule

